"""Generate practice calibration profiles for the control envelope.

These are SYNTHETIC. Each one walks a synthetic 30 Hz recording through the
real 60-second protocol plan (the helper the calibration tests use,
tests/test_calibration.py build_records), then scores it with the real
perception/calibration.py score_session() and build_profile(). Nothing here
was measured from a person: every profile carries "source": "synthetic" and
"measured": false from its recording header.

They exist so the frontend can be built before a real sample profile
arrives. Replace or extend them with real profiles when they exist.

Run from the repository root (needs pytest, from requirements.txt):

    python3 frontend/scripts/practice_profiles.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from perception import calibration  # noqa: E402
from tests.test_calibration import Channel, build_records  # noqa: E402

OUT = ROOT / "frontend" / "src" / "fixtures" / "calibration-profiles"

# Blendshape scores rest near 0.02; head angles rest near 0 except pitch,
# which Phase 2 measured resting at +9.8 degrees with a laptop camera.
PRACTICE = {
    "broad": {
        "about": "Broad mobility: brows, jaw, smile and all three head angles move well.",
        "channels": {
            "browInnerUp": Channel(probe="brows", amps=(0.45, 0.47, 0.44)),
            "jawOpen": Channel(probe="jaw", amps=(0.55, 0.57, 0.54)),
            "mouthSmileLeft": Channel(probe="smile", amps=(0.40, 0.41, 0.39)),
            "yaw_deg": Channel(rest=0.0, noise=0.3, probe="turn", amps=(28.0, 30.0, 29.0)),
            "pitch_deg": Channel(rest=9.8, noise=0.3, probe="nod", amps=(14.0, 15.0, 14.5)),
            "roll_deg": Channel(rest=0.0, noise=0.3, probe="tilt", amps=(16.0, 17.0, 16.5)),
        },
    },
    "two-narrow": {
        "about": "Two narrow channels: a small jaw opening and a small head turn.",
        "channels": {
            "jawOpen": Channel(probe="jaw", amps=(0.12, 0.13, 0.12)),
            "yaw_deg": Channel(rest=0.0, noise=0.3, probe="turn", amps=(6.0, 6.5, 6.2)),
        },
    },
    "single-eyebrow": {
        "about": "One eyebrow: only the outer left brow rises; nothing else moves.",
        "channels": {
            "browOuterUpLeft": Channel(probe="brows", amps=(0.22, 0.23, 0.22)),
        },
    },
}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, spec in PRACTICE.items():
        records = build_records(spec["channels"], calibration.PROBES)
        recording = calibration.parse_records(records)
        result = calibration.score_session(recording)
        profile = calibration.build_profile(result, recording)
        profile["practice_note"] = f"SYNTHETIC practice profile '{name}'. {spec['about']} Generated by frontend/scripts/practice_profiles.py."
        calibration.write_json(profile, OUT / f"{name}.json")
        tier = profile["proposed_tier"]
        bound = [(b["channel"], b["role"]) for b in profile["bindings"]]
        print(f"{name}: tier {tier['tier']} ({tier['mode']}), quality {profile['session_quality']}, bound {bound}")


if __name__ == "__main__":
    main()
