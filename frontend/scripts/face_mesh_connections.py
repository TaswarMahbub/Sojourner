"""Generate src/preview/faceMeshConnections.js from the installed MediaPipe package.

    python3 frontend/scripts/face_mesh_connections.py

The edge lists are MediaPipe's own Face Landmarker connections
(mediapipe.tasks.vision.FaceLandmarksConnections, Apache License 2.0).
They are index pairs over the 478 Face Landmarker landmarks; no landmark
data is included.
"""

from pathlib import Path

import mediapipe as mp

OUT = Path(__file__).resolve().parents[1] / "src" / "preview" / "faceMeshConnections.js"
C = mp.tasks.vision.FaceLandmarksConnections


def flat(edges):
    return ",".join(f"{e.start},{e.end}" for e in edges)


lines = [
    "// Generated by frontend/scripts/face_mesh_connections.py from MediaPipe "
    f"{mp.__version__} (mediapipe.tasks.vision.FaceLandmarksConnections, Apache License 2.0).",
    "// Flat [start, end, start, end, ...] index pairs over the 478 Face Landmarker landmarks. Do not edit.",
    "export const LANDMARK_COUNT = 478",
    f"export const TESSELATION = Object.freeze([{flat(C.FACE_LANDMARKS_TESSELATION)}])",
    f"export const CONTOURS = Object.freeze([{flat(C.FACE_LANDMARKS_CONTOURS)}])",
    "",
]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT}")
