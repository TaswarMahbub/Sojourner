import { describe, expect, it } from 'vitest'
import { decodeCalibrationProfile, validateCalibrationProfile } from './calibrationProfile.js'
import broad from '../fixtures/calibration-profiles/broad.json'
import twoNarrow from '../fixtures/calibration-profiles/two-narrow.json'
import singleEyebrow from '../fixtures/calibration-profiles/single-eyebrow.json'

const clone = (p) => structuredClone(p)
const errorsFor = (edit, base = singleEyebrow) => {
  const p = clone(base)
  edit(p)
  return validateCalibrationProfile(p).errors
}

describe('calibration profile, provisional schema 1', () => {
  it('accepts every practice profile generated by build_profile()', () => {
    for (const p of [broad, twoNarrow, singleEyebrow]) expect(validateCalibrationProfile(p)).toEqual({ valid: true, errors: [] })
  })

  it('rejects other record types and schema versions first', () => {
    expect(errorsFor((p) => { p.record_type = 'frame' })).toEqual(['record_type: expected "calibration_profile"'])
    expect(errorsFor((p) => { p.schema_version = 2 })).toEqual(['schema_version: expected 1 (provisional profile schema)'])
    expect(validateCalibrationProfile(null).valid).toBe(false)
  })

  it('checks the binding fields the envelope draws from', () => {
    expect(errorsFor((p) => { p.bindings[0].unit = 'mm' })).toEqual(['bindings[0].unit: must be one of score, deg, cm'])
    expect(errorsFor((p) => { p.bindings[0].effective_std = 0 })).toEqual(['bindings[0].effective_std: must be a number above 0'])
    expect(errorsFor((p) => { p.bindings[0].usable_range = null })).toEqual(['bindings[0].usable_range: must be a number above 0'])
    expect(errorsFor((p) => { p.bindings[0].direction = 0 })).toEqual(['bindings[0].direction: must be 1 or -1'])
    expect(errorsFor((p) => { delete p.bindings[0].threshold })).toEqual(['bindings[0].threshold.offset: must be a number >= 0'])
    expect(errorsFor((p) => { p.bindings[0].role = 'turbo' })).toHaveLength(1)
  })

  it('requires the tier and mode to agree', () => {
    expect(errorsFor((p) => { p.proposed_tier.mode = 'proportional' })).toEqual(['proposed_tier.mode: tier 3 is "scanning"'])
    expect(errorsFor((p) => { p.proposed_tier.tier = 4 })).toEqual(['proposed_tier.tier: must be 1, 2, 3 or null'])
  })

  it('requires disqualified channels to carry reasons, and only them', () => {
    const row = singleEyebrow.enrolment_metrics.ranking.findIndex((r) => r.status === 'disqualified')
    expect(errorsFor((p) => { p.enrolment_metrics.ranking[row].reasons = [] })).toHaveLength(1)
    expect(errorsFor((p) => { p.enrolment_metrics.ranking[0].reasons = ['snr_below_floor'] })).toHaveLength(1)
    expect(errorsFor((p) => { p.enrolment_metrics.ranking[0].status = 'great' })).toHaveLength(1)
  })

  it('checks the parts agree: bound means ranked usable; tier 3 binds one channel', () => {
    expect(errorsFor((p) => { p.enrolment_metrics.ranking[0].status = 'redundant'; p.enrolment_metrics.ranking[0].redundant_with = 'x' }))
      .toContain('bindings: "browOuterUpLeft" is bound but not ranked usable')
    expect(errorsFor((p) => { p.bindings.push(clone(p.bindings[0])) })).toContain('bindings: a channel is bound twice')
  })

  it('a suspect profile must have no bindings and no tier', () => {
    expect(errorsFor((p) => { p.session_quality = 'suspect' })).toEqual(['session_quality: a suspect profile has no bindings and no tier'])
    const ok = errorsFor((p) => {
      p.session_quality = 'suspect'
      p.bindings = []
      p.proposed_tier = { tier: null, mode: null, reason: 'rest suspect' }
      p.enrolment_metrics.ranking[0].status = 'disqualified'
      p.enrolment_metrics.ranking[0].reasons = ['rest_suspect']
    })
    expect(ok).toEqual([])
  })

  it('allows fields it does not use, because the format is provisional', () => {
    expect(errorsFor((p) => { p.something_new = 1 })).toEqual([])
  })

  it('decodes text strictly', () => {
    expect(decodeCalibrationProfile(JSON.stringify(singleEyebrow)).valid).toBe(true)
    expect(decodeCalibrationProfile('{"a": 1, "a": 2}').valid).toBe(false)
    expect(decodeCalibrationProfile('not json')).toMatchObject({ valid: false, profile: null })
  })
})
